def build_2d_gine_graph(mol, atomic_df):
    """Topology-only GINE graph using the same node features as the corrected 3D-GINE.

    The only architectural difference from 3D-GINE is omission of the bond-length edge feature
    (7 edge features instead of 8). Explicit H atoms are retained to keep graph topology/node
    treatment aligned with the 3D model, but their coordinates are not used.
    """
    import torch
    from rdkit import Chem
    from rdkit.Chem import rdPartialCharges

    if mol is None:
        return None
    mol = Chem.AddHs(mol)
    try:
        rdPartialCharges.ComputeGasteigerCharges(mol)
    except Exception:
        pass

    node_features = []
    for atom in mol.GetAtoms():
        symbol = atom.GetSymbol()
        if symbol not in ALLOWED_ELEMENTS:
            return None
        atom_feat = atomic_df.loc[symbol].values.tolist() if symbol in atomic_df.index else np.zeros(atomic_df.shape[1]).tolist()
        try:
            g_charge = atom.GetDoubleProp('_GasteigerCharge')
            if np.isnan(g_charge) or np.isinf(g_charge):
                g_charge = 0.0
        except Exception:
            g_charge = 0.0
        hybridization = one_hot_encoding(str(atom.GetHybridization()), ['SP', 'SP2', 'SP3', 'SP3D', 'SP3D2', 'Unknown'])
        degree = one_hot_encoding(atom.GetDegree(), [0, 1, 2, 3, 4, 5, 6, 'Unknown'])
        formal_charge = [atom.GetFormalCharge()]
        aromatic = [1 if atom.GetIsAromatic() else 0]
        in_ring = [1 if atom.IsInRing() else 0]
        num_hs = one_hot_encoding(atom.GetTotalNumHs(), [0, 1, 2, 3, 4, 'Unknown'])
        node_features.append(atom_feat + [g_charge] + hybridization + degree + formal_charge + aromatic + in_ring + num_hs)

    x = torch.tensor(node_features, dtype=torch.float32)
    edge_index, edge_features = [], []
    for bond in mol.GetBonds():
        i, j = bond.GetBeginAtomIdx(), bond.GetEndAtomIdx()
        bond_type = one_hot_encoding(str(bond.GetBondType()), ['SINGLE', 'DOUBLE', 'TRIPLE', 'AROMATIC', 'Unknown'])
        bond_in_ring = [1 if bond.IsInRing() else 0]
        conj = [1 if bond.GetIsConjugated() else 0]
        ef = bond_type + bond_in_ring + conj
        edge_index += [[i, j], [j, i]]
        edge_features += [ef, ef]

    edge_index = torch.tensor(edge_index, dtype=torch.long).t().contiguous() if edge_index else torch.zeros((2, 0), dtype=torch.long)
    edge_attr = torch.tensor(edge_features, dtype=torch.float32) if edge_features else torch.zeros((0, 7), dtype=torch.float32)
    if torch.isnan(x).any() or torch.isnan(edge_attr).any():
        return None
    return {'x': x, 'edge_index': edge_index, 'edge_attr': edge_attr}


def build_schnet_geometry(mol):
    """Corrected SchNet geometry with explicit H coordinates generated by RDKit.

    This directly fixes the same hydrogen-coordinate issue identified for the original 3D-GINE,
    which is even more consequential for SchNet because SchNet consumes atomic coordinates.
    """
    import torch
    from rdkit import Chem

    if mol is None:
        return None
    mol = Chem.AddHs(mol, addCoords=True)
    try:
        conf = mol.GetConformer()
    except ValueError:
        return None

    z_list, pos_list = [], []
    for i, atom in enumerate(mol.GetAtoms()):
        if atom.GetSymbol() not in ALLOWED_ELEMENTS:
            return None
        z_list.append(atom.GetAtomicNum())
        p = conf.GetAtomPosition(i)
        xyz = [float(p.x), float(p.y), float(p.z)]
        if not np.all(np.isfinite(xyz)):
            return None
        pos_list.append(xyz)

    return {
        'z': torch.tensor(z_list, dtype=torch.long),
        'pos': torch.tensor(pos_list, dtype=torch.float32),
    }


def extract_structure_descriptors(mol):
    """Original 16-dimensional 3D/topological descriptor branch used for the 3D-MLP baseline."""
    from rdkit.Chem import Descriptors, rdMolDescriptors

    if mol is None or mol.GetNumConformers() == 0:
        return None
    for atom in mol.GetAtoms():
        if atom.GetSymbol() not in ALLOWED_ELEMENTS:
            return None
    try:
        vals = [
            rdMolDescriptors.CalcAsphericity(mol),
            rdMolDescriptors.CalcEccentricity(mol),
            rdMolDescriptors.CalcInertialShapeFactor(mol),
            rdMolDescriptors.CalcNPR1(mol),
            rdMolDescriptors.CalcNPR2(mol),
            rdMolDescriptors.CalcPMI1(mol),
            rdMolDescriptors.CalcPMI2(mol),
            rdMolDescriptors.CalcPMI3(mol),
            rdMolDescriptors.CalcRadiusOfGyration(mol),
            rdMolDescriptors.CalcSpherocityIndex(mol),
            Descriptors.BalabanJ(mol),
            Descriptors.BertzCT(mol),
            Descriptors.Chi1v(mol),
            Descriptors.Kappa2(mol),
            Descriptors.FractionCSP3(mol),
            Descriptors.RingCount(mol),
        ]
        vals = np.asarray(vals, dtype=float)
        return vals if np.all(np.isfinite(vals)) else None
    except Exception:
        return None


def prepare_architecture_common_data(df, sdf_dir, atomic_df):
    """Build all four representations from the SAME corrected 3D SDF source and retain only common rows.

    Using one molecular source avoids a hidden data-availability confound between 2D and 3D models.
    2D-GINE ignores coordinates; 3D-GINE adds bond length; SchNet uses coordinates; 3D-MLP uses
    the manuscript's 16 handcrafted 3D/topological descriptors.
    """
    from rdkit import Chem
    from rdkit.Chem import Descriptors

    sdf_dir = Path(sdf_dir)
    cache: Dict[str, dict | None] = {}
    valid_rows: List[int] = []
    g2d_rows, g3d_rows, sch_rows, struct_rows, moltab_rows = [], [], [], [], []

    for i, row in df.iterrows():
        key = str(row['Number'])
        if key not in cache:
            sdf = sdf_dir / f'{key}.sdf'
            rep = None
            if sdf.exists():
                try:
                    supplier = Chem.SDMolSupplier(str(sdf))  # removeHs=True, same as corrected core pipeline
                    mol = next(iter(supplier)) if supplier else None
                    if mol is not None:
                        g2d = build_2d_gine_graph(mol, atomic_df)
                        g3d = build_3d_gine_graph(mol, atomic_df)
                        sch = build_schnet_geometry(mol)
                        struct = extract_structure_descriptors(mol)
                        moltab = np.asarray([
                            Descriptors.MolWt(mol),
                            Descriptors.TPSA(mol),
                            Descriptors.MolLogP(mol),
                        ], dtype=float)
                        if g2d is not None and g3d is not None and sch is not None and struct is not None and np.all(np.isfinite(moltab)):
                            rep = dict(g2d=g2d, g3d=g3d, schnet=sch, struct=struct, moltab=moltab)
                except Exception:
                    rep = None
            cache[key] = rep

        rep = cache[key]
        if rep is None:
            continue
        valid_rows.append(i)
        g2d_rows.append(rep['g2d'])
        g3d_rows.append(rep['g3d'])
        sch_rows.append(rep['schnet'])
        struct_rows.append(rep['struct'])
        moltab_rows.append(rep['moltab'])

    out_df = df.loc[valid_rows].copy().reset_index(drop=True)
    if len(out_df) != len(df):
        raise ValueError(f'Architecture construction lost {len(df)-len(out_df)} input rows. Repair structures before the paired 12-model benchmark.')
    return {
        'df': out_df,
        'g2d': g2d_rows,
        'g3d': g3d_rows,
        'schnet': sch_rows,
        'struct': np.asarray(struct_rows, dtype=float),
        'moltab': np.asarray(moltab_rows, dtype=float),
    }


def make_mlp_dataset_class():
    import torch
    from torch.utils.data import Dataset

    class MultiModalDataset(Dataset):
        def __init__(self, x_struct, x_mol, x_env_cont, x_env_sp, x_env_ex, y, row_ids):
            self.x_struct = torch.tensor(x_struct, dtype=torch.float32)
            self.x_mol = torch.tensor(x_mol, dtype=torch.float32)
            self.x_env_cont = torch.tensor(x_env_cont, dtype=torch.float32)
            self.x_env_sp = torch.tensor(x_env_sp, dtype=torch.long)
            self.x_env_ex = torch.tensor(x_env_ex, dtype=torch.long)
            self.y = torch.tensor(y, dtype=torch.float32)
            self.row_ids = torch.tensor(row_ids, dtype=torch.long)

        def __len__(self):
            return len(self.y)

        def __getitem__(self, idx):
            return (
                self.x_struct[idx], self.x_mol[idx], self.x_env_cont[idx],
                self.x_env_sp[idx], self.x_env_ex[idx], self.y[idx], self.row_ids[idx]
            )

    return MultiModalDataset


def make_mlp_model_class():
    import torch
    from torch import nn

    class MultiBranchMLPModel(nn.Module):
        def __init__(self, dim_struct, dim_mol, num_species, num_exposure, hidden_dims, dropout):
            super().__init__()
            h1, h2 = hidden_dims
            self.fc_struct = nn.Sequential(
                nn.Linear(dim_struct, 16), nn.BatchNorm1d(16), nn.SiLU(),
                nn.Linear(16, h1), nn.SiLU(),
            )
            self.fc_mol = nn.Sequential(
                nn.Linear(dim_mol, 16), nn.BatchNorm1d(16), nn.SiLU(),
                nn.Linear(16, 16), nn.SiLU(),
            )
            emb_dim_sp = min(50, (num_species + 1) // 2)
            emb_dim_ex = min(10, (num_exposure + 1) // 2)
            self.emb_species = nn.Embedding(num_species, emb_dim_sp)
            self.emb_exposure = nn.Embedding(num_exposure, emb_dim_ex)
            self.dropout = nn.Dropout(dropout)
            self.fc_env = nn.Sequential(nn.Linear(1 + emb_dim_sp + emb_dim_ex, h1), nn.BatchNorm1d(h1), nn.SiLU())
            self.fc_joint = nn.Sequential(nn.Linear(h1 + 16 + h1, h2), nn.BatchNorm1d(h2), nn.SiLU())
            self.fc_out = nn.Linear(h2, 1)

        def forward(self, x_struct, x_mol, x_env_cont, x_env_sp, x_env_ex):
            s = self.dropout(self.fc_struct(x_struct))
            m = self.dropout(self.fc_mol(x_mol))
            sp = self.emb_species(x_env_sp.view(-1))
            ex = self.emb_exposure(x_env_ex.view(-1))
            e = self.dropout(self.fc_env(torch.cat([x_env_cont, sp, ex], dim=1)))
            return self.fc_out(self.fc_joint(torch.cat([s, m, e], dim=1))).view(-1)

    return MultiBranchMLPModel


def make_schnet_dataset_class():
    import torch
    from torch.utils.data import Dataset
    from torch_geometric.data import Data

    class SchNetDataset(Dataset):
        def __init__(self, geoms, x_mol, x_env_cont, x_env_sp, x_env_ex, y, row_ids):
            self.items = []
            for g, tm, ec, sp, ex, yy, rid in zip(geoms, x_mol, x_env_cont, x_env_sp, x_env_ex, y, row_ids):
                self.items.append(Data(
                    z=g['z'], pos=g['pos'],
                    tab_mol=torch.tensor(tm, dtype=torch.float32).unsqueeze(0),
                    tab_env_cont=torch.tensor(ec, dtype=torch.float32).unsqueeze(0),
                    tab_env_sp=torch.tensor([sp], dtype=torch.long),
                    tab_env_ex=torch.tensor([ex], dtype=torch.long),
                    y=torch.tensor(float(yy), dtype=torch.float32),
                    row_id=torch.tensor([int(rid)], dtype=torch.long),
                ))

        def __len__(self):
            return len(self.items)

        def __getitem__(self, idx):
            return self.items[idx]

    return SchNetDataset


def schnet_collate(batch):
    from torch_geometric.data import Batch
    return Batch.from_data_list(batch)


def make_schnet_model_class():
    from torch import nn
    from torch_geometric.nn import SchNet, global_max_pool

    class MultiBranchSchNetModel(nn.Module):
        def __init__(self, mol_dim, num_species, num_exposure, schnet_hidden, num_interactions,
                     num_gaussians, cutoff, hidden_dims, dropout):
            super().__init__()
            self.schnet = SchNet(
                hidden_channels=schnet_hidden,
                num_filters=schnet_hidden,
                num_interactions=num_interactions,
                num_gaussians=num_gaussians,
                cutoff=cutoff,
                readout='mean',
            )
            # Preserve the original study's mean+max readout design.
            self.schnet.lin2 = nn.Identity()
            self._node_features = None

            def hook_fn(module, inputs, output):
                self._node_features = output

            self.schnet.lin2.register_forward_hook(hook_fn)
            h1, h2 = hidden_dims
            schnet_out_dim = (schnet_hidden // 2) * 2
            self.dropout = nn.Dropout(dropout)
            self.fc_graph = nn.Sequential(nn.Linear(schnet_out_dim, h1), nn.BatchNorm1d(h1), nn.SiLU())
            self.fc_mol = nn.Sequential(
                nn.Linear(mol_dim, 16), nn.BatchNorm1d(16), nn.SiLU(),
                nn.Linear(16, 16), nn.SiLU(),
            )
            emb_dim_sp = min(50, (num_species + 1) // 2)
            emb_dim_ex = min(10, (num_exposure + 1) // 2)
            self.emb_species = nn.Embedding(num_species, emb_dim_sp)
            self.emb_exposure = nn.Embedding(num_exposure, emb_dim_ex)
            self.fc_env = nn.Sequential(nn.Linear(1 + emb_dim_sp + emb_dim_ex, h1), nn.BatchNorm1d(h1), nn.SiLU())
            self.fc_joint = nn.Sequential(nn.Linear(h1 + 16 + h1, h2), nn.BatchNorm1d(h2), nn.SiLU())
            self.fc_out = nn.Linear(h2, 1)

        def forward(self, z, pos, batch, tab_mol, tab_env_cont, tab_env_sp, tab_env_ex):
            g_mean = self.schnet(z, pos, batch)
            h = self._node_features
            if h is None:
                raise RuntimeError('SchNet node-feature hook did not fire.')
            g_max = global_max_pool(h, batch)
            g = self.dropout(self.fc_graph(__import__('torch').cat([g_mean, g_max], dim=-1)))
            m = self.dropout(self.fc_mol(tab_mol))
            sp = self.emb_species(tab_env_sp.view(-1))
            ex = self.emb_exposure(tab_env_ex.view(-1))
            e = self.dropout(self.fc_env(__import__('torch').cat([tab_env_cont, sp, ex], dim=1)))
            return self.fc_out(self.fc_joint(__import__('torch').cat([g, m, e], dim=1))).view(-1)

    return MultiBranchSchNetModel


def evaluate_mlp(model, loader, criterion, device):
    model.eval()
    preds, trues, rowids, losses = [], [], [], []
    import torch
    with torch.no_grad():
        for xs, xm, xe, sp, ex, y, rid in loader:
            xs, xm, xe, sp, ex, y = [v.to(device) for v in (xs, xm, xe, sp, ex, y)]
            p = model(xs, xm, xe, sp, ex)
            losses.append(float(criterion(p, y).item()))
            preds.extend(p.detach().cpu().numpy().tolist())
            trues.extend(y.detach().cpu().numpy().tolist())
            rowids.extend(rid.numpy().astype(int).tolist())
    return float(np.mean(losses)) if losses else np.nan, preds, trues, rowids


def evaluate_schnet(model, loader, criterion, device):
    import torch
    model.eval()
    preds, trues, rowids, losses = [], [], [], []
    with torch.no_grad():
        for b in loader:
            b = b.to(device)
            p = model(b.z, b.pos, b.batch, b.tab_mol, b.tab_env_cont, b.tab_env_sp, b.tab_env_ex)
            losses.append(float(criterion(p, b.y).item()))
            preds.extend(p.detach().cpu().numpy().tolist())
            trues.extend(b.y.detach().cpu().numpy().tolist())
            rowids.extend(b.row_id.view(-1).detach().cpu().numpy().astype(int).tolist())
    return float(np.mean(losses)) if losses else np.nan, preds, trues, rowids


def count_parameters(model) -> int:
    return int(sum(p.numel() for p in model.parameters() if p.requires_grad))
